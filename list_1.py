##A list stores multiple values and can be modified (mutable).

# max()
#Finds highest mark

marks = [55,25,64,52]
print(max(marks))

#min()
#Finds lowest mark.
marks = [52,6,63,36,6]
print(min(marks)) 

#sum()
#Adds all numbers.
marks=[88,233,12,6,1]
print(sum(marks))

#len()
#Counts total elements.
marks=[5555,666,6,33,33,3]
print(len(marks))

#Average = Total / Number of Students
marks=[545,55,5,5,55]
average=sum(marks)/len(marks)
print(average)